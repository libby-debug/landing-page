create or replace function public.apply_api_table_grants(target_table regclass)
returns void
language plpgsql
as $$
begin
  execute format('grant select on table %s to anon', target_table);
  execute format(
    'grant select, insert, update, delete on table %s to authenticated',
    target_table
  );
  execute format(
    'grant select, insert, update, delete on table %s to service_role',
    target_table
  );
end;
$$;

create or replace function public.apply_authenticated_sequence_grants(
  target_sequence regclass
)
returns void
language plpgsql
as $$
begin
  execute format(
    'grant usage, select on sequence %s to authenticated',
    target_sequence
  );
  execute format(
    'grant usage, select on sequence %s to service_role',
    target_sequence
  );
end;
$$;

comment on function public.apply_api_table_grants(regclass)
is 'Reusable migration helper for Supabase API table grants. Call immediately after create table, then enable RLS and add owner-scoped policies.';

comment on function public.apply_authenticated_sequence_grants(regclass)
is 'Reusable migration helper for autogenerated ID sequences tied to public tables.';

