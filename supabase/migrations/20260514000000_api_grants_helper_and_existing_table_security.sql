  on public.module_mastery_scores;
create policy "Users can read their own module mastery scores"
  on public.module_mastery_scores
  for select
  using (auth.uid() = user_id);

drop policy if exists "Users can insert their own module mastery scores"
  on public.module_mastery_scores;
